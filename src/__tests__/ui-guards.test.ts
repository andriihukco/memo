import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync, statSync } from 'fs';
import path from 'path';

const ROOT = path.resolve(__dirname, '../..');

const RULES: [string, RegExp][] = [
  ['arbitrary text size', /text-\[\d+px\]/],
  ['arbitrary colour class', /(bg|text|border)-\[#/],
  ['hex colour', /#[0-9a-fA-F]{6}\b/],
  ['muted-foreground opacity', /muted-foreground\/\d+/],
  ['click handler on div/span', /<(div|span)[^>]*onClick/],
  ['framer-motion import', /from ['"]framer-motion['"]/],
  ['arbitrary radius', /rounded-\[/],
  ['arbitrary z-index', /z-\[/],
];

// Files generated by the shadcn CLI in src/components/ui; everything else there is an old custom.
const SHADCN_FILES = new Set([
  'alert-dialog', 'alert', 'avatar', 'badge', 'button', 'calendar', 'card', 'chart', 'command',
  'context-menu', 'dialog', 'drawer', 'dropdown-menu', 'form', 'input-otp', 'input', 'label',
  'popover', 'progress', 'scroll-area', 'select', 'separator', 'skeleton', 'sonner', 'switch',
  'tabs', 'textarea', 'toggle-group', 'toggle',
].map((n) => `src/components/ui/${n}.tsx`));

const EXEMPT = ['confetti.tsx', 'splash-screen.tsx'];

// Entries ending in "/" are directory prefixes. Phase 1 removes entries; Phase 2 empties it.
export const LEGACY_ALLOWLIST: string[] = [
  'src/components/legacy/',
  'src/components/features/',
  'src/app/miniapp/',
  'src/components/ui/bottom-sheet.tsx',
  'src/components/ui/confirm-sheet.tsx',
  'src/components/ui/edit-drawer.tsx',
  'src/components/ui/empty-state.tsx',
  'src/components/ui/error-banner.tsx',
  'src/components/ui/passcode-screen.tsx',
  'src/components/ui/paywall-modal.tsx',
  'src/components/ui/undo-toast.tsx',
  'src/components/ui/usage-counter-chip.tsx',
  'src/components/ui/usage-warning-banner.tsx',
];

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((n) => {
    const p = path.join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.tsx') ? [p] : [];
  });
}

const allowed = (rel: string) =>
  LEGACY_ALLOWLIST.some((a) => (a.endsWith('/') ? rel.startsWith(a) : rel === a));

const files = ['src/app', 'src/components']
  .flatMap((d) => walk(path.join(ROOT, d)))
  .map((p) => path.relative(ROOT, p))
  .filter((rel) => !SHADCN_FILES.has(rel) && !EXEMPT.some((e) => rel.endsWith(e)) && !allowed(rel));

describe('ui style guards', () => {
  it('scans some files', () => expect(files.length).toBeGreaterThan(0));
  for (const [name, re] of RULES) {
    it(`no ${name} (${re})`, () => {
      const bad = files.filter((rel) => re.test(readFileSync(path.join(ROOT, rel), 'utf8')));
      expect(bad).toEqual([]);
    });
  }
});
